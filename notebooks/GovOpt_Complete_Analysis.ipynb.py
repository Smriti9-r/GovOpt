# GOVOPT: PRELIMINARY DISTRICT NEED SCORE

need_data = priority_evidence[
    [
        "district",
        "education_enrolment_per_school",
        "water_adequacy",
        "functional_tap_connections",
        "water_regularity",
        "water_quantity_satisfaction"
    ]
].copy()

# 1. Normalise education pressure
education_min = need_data[
    "education_enrolment_per_school"
].min()

education_max = need_data[
    "education_enrolment_per_school"
].max()

need_data["education_need"] = (
    (need_data["education_enrolment_per_school"] - education_min) /
    (education_max - education_min) * 100
)

# 2. Convert water service percentages into gap scores
need_data["water_adequacy_need"] = (
    100 - need_data["water_adequacy"]
)

need_data["functional_connection_need"] = (
    100 - need_data["functional_tap_connections"]
)

need_data["water_regularity_need"] = (
    100 - need_data["water_regularity"]
)

need_data["water_satisfaction_need"] = (
    100 - need_data["water_quantity_satisfaction"]
)

# 3. Calculate equally weighted preliminary score
need_indicators = [
    "education_need",
    "water_adequacy_need",
    "functional_connection_need",
    "water_regularity_need",
    "water_satisfaction_need"
]

need_data["preliminary_need_score"] = (
    need_data[need_indicators].mean(axis=1)
).round(2)

# 4. Rank districts
need_data = need_data.sort_values(
    "preliminary_need_score",
    ascending=False
).reset_index(drop=True)

need_data["priority_rank"] = (
    need_data.index + 1
)

display(need_data.round(2))

need_data.to_csv(
    "GovOpt_Preliminary_District_Need_Scores.csv",
    index=False
)

print("Preliminary need scores generated!")

# GOVOPT: SECTOR-BALANCED NEED MODEL

balanced_need = need_data.copy()

# Education contributes 50%
balanced_need["education_weighted"] = (
    balanced_need["education_need"] * 0.50
)

# Water contributes 50%, divided equally across four indicators
water_indicators = [
    "water_adequacy_need",
    "functional_connection_need",
    "water_regularity_need",
    "water_satisfaction_need"
]

balanced_need["water_weighted"] = (
    balanced_need[water_indicators].mean(axis=1) * 0.50
)

# Final score
balanced_need["balanced_need_score"] = (
    balanced_need["education_weighted"] +
    balanced_need["water_weighted"]
).round(2)

balanced_need = balanced_need.sort_values(
    "balanced_need_score",
    ascending=False
).reset_index(drop=True)

